CREATE TABLE ALERT_CONFIGS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MONITOR_ID NUMBER NOT NULL,
    CHANNEL VARCHAR2(20) DEFAULT 'EMAIL' NOT NULL,
    RECIPIENT VARCHAR2(320) NOT NULL,
    ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
    ON_FAILURE NUMBER(1) DEFAULT 1 NOT NULL,
    ON_RECOVERY NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT FK_ALERT_MONITOR FOREIGN KEY (MONITOR_ID) REFERENCES MONITORS(ID),
    CONSTRAINT CK_ALERT_CHANNEL CHECK (CHANNEL IN ('EMAIL'))
);

CREATE INDEX IX_ALERT_MONITOR ON ALERT_CONFIGS(MONITOR_ID);
