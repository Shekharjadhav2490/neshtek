CREATE TABLE MONITORS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(120) NOT NULL,
    URL VARCHAR2(2048) NOT NULL,
    CHECK_INTERVAL_SECONDS NUMBER(10) DEFAULT 300 NOT NULL,
    TIMEOUT_SECONDS NUMBER(10) DEFAULT 15 NOT NULL,
    EXPECTED_STATUS NUMBER(3) DEFAULT 200 NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT CK_MONITORS_STATUS CHECK (STATUS IN ('ACTIVE', 'PAUSED'))
);

CREATE TABLE INCIDENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MONITOR_ID NUMBER NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    HTTP_STATUS NUMBER(3),
    RESPONSE_TIME_MS NUMBER(19),
    ERROR_MESSAGE VARCHAR2(2000),
    STARTED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    RESOLVED_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT FK_INCIDENT_MONITOR FOREIGN KEY (MONITOR_ID) REFERENCES MONITORS(ID),
    CONSTRAINT CK_INCIDENT_STATUS CHECK (STATUS IN ('OPEN', 'RESOLVED'))
);

CREATE INDEX IX_INCIDENT_MONITOR ON INCIDENTS(MONITOR_ID);
CREATE INDEX IX_INCIDENT_STATUS ON INCIDENTS(STATUS);
