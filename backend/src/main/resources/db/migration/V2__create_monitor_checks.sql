CREATE TABLE MONITOR_CHECKS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MONITOR_ID NUMBER NOT NULL,
    HTTP_STATUS NUMBER(3),
    RESPONSE_TIME_MS NUMBER(19),
    OUTCOME VARCHAR2(30) NOT NULL,
    ERROR_MESSAGE VARCHAR2(2000),
    CHECKED_AT TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_CHECK_MONITOR FOREIGN KEY (MONITOR_ID) REFERENCES MONITORS(ID)
);

CREATE INDEX IX_CHECK_MONITOR_TIME ON MONITOR_CHECKS(MONITOR_ID, CHECKED_AT);
CREATE INDEX IX_CHECK_OUTCOME ON MONITOR_CHECKS(OUTCOME);
